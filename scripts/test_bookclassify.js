cat('魔戒', '托尔金', '科幻·奇幻');
cat('哈利波特与魔法石', 'J.K.罗琳', '科幻·奇幻');
cat('赛博朋克', '', '科幻·奇幻');

cat('白夜行', '东野圭吾', '推理·悬疑');
cat('无人生还', '阿加莎·克里斯蒂', '推理·悬疑');
