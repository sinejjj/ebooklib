/* ---------------- E. 该留空的必须留空 ---------------- */
eq('E1 空书名 → 未分类', BC.classify('', ''), '');
eq('E2 空作者也能量力而行', BC.classify('活着'), '文学·小说');
eq('E3 纯编号 → 未分类', BC.classify('2731', ''), '');
eq('E4 无信息量短词 → 未分类', BC.classify('备忘', ''), '');
eq('E5 「我的历史」不因弱词被带走', BC.classify('我的历史', ''), '');

/* ---------------- F. 旧分类迁移 ---------------- */
eq('F1 社会·纪实·新闻 → 社会·文化',
  BC.migrate('社会·纪实·新闻', '', ''), '社会·文化');
eq('F2 传记·回忆录·口述 → 历史·纪实',
  BC.migrate('传记·回忆录·口述', '', ''), '历史·纪实');
eq('F3 心理·认知·思维 → 心理·认知',
  BC.migrate('心理·认知·思维', '', ''), '心理·认知');
eq('F4 历史·地理 偏地理 → 地理·旅行',
  BC.migrate('历史·地理', '走过西藏', ''), '地理·旅行');
eq('F5 历史·地理 偏历史 → 历史·纪实',
  BC.migrate('历史·地理', '万历十五年', '黄仁宇'), '历史·纪实');
eq('F6 政治·哲学·军事 偏哲学 → 哲学·宗教',
  BC.migrate('政治·哲学·军事', '理想国', '柏拉图'), '哲学·宗教');
eq('F7 政治·哲学·军事 偏军事 → 政治·军事',
  BC.migrate('政治·哲学·军事', '战争论', '克劳塞维茨'), '政治·军事');
eq('F8 已在新表里的原样返回', BC.migrate('推理·悬疑', '', ''), '推理·悬疑');
eq('F9 待归类 → 空', BC.migrate('待归类·资料杂项', '', ''), '');
eq('F10 空值 → 空', BC.migrate('', '', ''), '');

/* ---------------- G. 外部原始分类映射 ---------------- */
eq('G1 小说 → 文学·小说', BC.mapRaw('小说'), '文学·小说');
eq('G2 传记 → 历史·纪实', BC.mapRaw('传记'), '历史·纪实');
eq('G3 经管 → 商业·经济·管理', BC.mapRaw('经管'), '商业·经济·管理');
eq('G4 英文 fiction', BC.mapRaw('Fiction'), '文学·小说');
eq('G5 复合标签取首个可识别段', BC.mapRaw('小说/文学'), '文学·小说');
eq('G6 无意义标签 → 空', BC.mapRaw('其他'), '');
eq('G7 13 类原名直通', BC.mapRaw('心理·认知'), '心理·认知');

/* ---------------- H. 大组归属 ---------------- */
eq('H1 推理属文学作品', BC.groupOf('推理·悬疑'), '文学作品');
eq('H2 心理属人文与社会', BC.groupOf('心理·认知'), '人文与社会');
eq('H3 设计属知识与实践', BC.groupOf('设计·艺术·摄影'), '知识与实践');
eq('H4 未分类无大组', BC.groupOf('未分类'), '');

/* ---------------- 输出 ---------------- */
