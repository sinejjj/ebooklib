cat('走过西藏', '', '地理·旅行');
cat('寻路中国', '何伟', '历史·纪实');  /* 纪实游记，作者白名单优先 */
cat('游记', '', '地理·旅行');

cat('厌女', '上野千鹤子', '社会·文化');
