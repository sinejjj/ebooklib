#!/usr/bin/env node
/* bookclassify.js 纯逻辑单测（零依赖，Node 直接跑）
   用法： node scripts/test_bookclassify.js */
'use strict';

const BC = require('./bookclassify.js');

let pass = 0, fail = 0;
const fails = [];
function ok(name, cond, extra) {
  if (cond) { pass++; return; }
  fail++;
  fails.push(name + (extra === undefined ? '' : '  →  ' + JSON.stringify(extra)));
}
function eq(name, got, want) { ok(name, JSON.stringify(got) === JSON.stringify(want), { got, want }); }
function cat(title, author, want) {
  const got = BC.classify(title, author || '');
  ok('分类「' + title + '」→ ' + want, got === want, { got, want });
}

/* ---------------- A. 结构完整性 ---------------- */
eq('A1 分类共 13 个', BC.CATS.length, 13);
eq('A2 分类不重复', new Set(BC.CATS).size, 13);
const inGroups = [];
BC.GROUPS.forEach(g => inGroups.push(...g.cats));
eq('A3 三个大组覆盖全部 13 类', inGroups.length, 13);
ok('A4 大组与分类一一对应', inGroups.every(c => BC.CATS.includes(c)) &&
  BC.CATS.every(c => inGroups.includes(c)), { inGroups });
eq('A5 大组名', BC.GROUPS.map(g => g.name), ['文学作品', '人文与社会', '知识与实践']);
eq('A6 大组内数量 3/6/4', BC.GROUPS.map(g => g.cats.length), [3, 6, 4]);

/* ---------------- B. 文学三兄弟 ---------------- */
