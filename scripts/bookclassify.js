  var STOP = /^(我的|你的|我们的)?(历史|故事|记忆|人生)$/;

  function norm(s) {
    return String(s == null ? '' : s)
      .replace(/[\s\u3000]+/g, ' ')
      .replace(/[《》〈〉「」『』【】\[\]]/g, '')
      .trim();
  }

  /* 单条打分：返回 {cat, score} */
  function score(title, author) {
    var t = norm(title), a = norm(author);
    var sc = {};
    if (!t) return { cat: '', score: 0 };

    /* L1 常见书名：精确 6 / 包含 5 */
    for (var i = 0; i < COMMON.length; i++) {
      var key = COMMON[i][0], cat = COMMON[i][1];
      var hit = (EXACT[key] ? t === key : t.indexOf(key) >= 0);
      if (hit) {
        var w = EXACT[key] ? 6 : 5;
        if (!sc[cat] || sc[cat] < w) sc[cat] = w;
      }
    }

    /* L2 题材强词：每个命中 4 分，同类最多计两个 */
    for (var c in STRONG) {
      var n = 0;
      for (var j = 0; j < STRONG[c].length; j++) {
        if (t.indexOf(STRONG[c][j]) >= 0) n++;
      }
      if (n) sc[c] = (sc[c] || 0) + 4 * Math.min(n, 2);
    }

    /* L3 作者白名单：3 分 */
    if (a) {
      for (var c2 in AUTHOR) {
        for (var k = 0; k < AUTHOR[c2].length; k++) {
          if (a.indexOf(AUTHOR[c2][k]) >= 0) { sc[c2] = (sc[c2] || 0) + 3; break; }
        }
      }
    }

    var best = '', bs = 0, second = 0;
    for (var c4 in sc) {
      if (sc[c4] > bs) { second = bs; bs = sc[c4]; best = c4; }
      else if (sc[c4] > second) second = sc[c4];
    }
    if (best && bs >= 3 && bs > second) return { cat: best, score: bs };

    /* L4 弱词：1 分，只在没有更强信号时担任唯一候选 */
    var w1 = '', w1s = 0, w2s = 0;
    for (var c5 in WEAK) {
      for (var m = 0; m < WEAK[c5].length; m++) {
        if (t.indexOf(WEAK[c5][m]) >= 0) {
          if (!w1s) { w1 = c5; w1s = 1; }
          else if (c5 !== w1) { w2s = 1; }
          break;
        }
      }
    }
    if (w1 && !w2s && !STOP.test(t) && t.length >= 3) return { cat: w1, score: 1 };
    return { cat: '', score: bs };
  }

