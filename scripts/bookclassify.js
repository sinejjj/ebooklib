  function mapRaw(raw) {
    var s = norm(raw);
    if (!s || s.length > 24) return '';
    if (CATS.indexOf(s) >= 0) return s;
    var low = s.toLowerCase();
    if (RAW_MAP[low]) return RAW_MAP[low];
    var parts = s.split(/[\/、,，|·\s]+/).filter(Boolean);
    for (var i = 0; i < parts.length; i++) {
      var p = parts[i].toLowerCase();
      if (RAW_MAP[p]) return RAW_MAP[p];
      for (var k = 0; k < CATS.length; k++) {
        if (CATS[k].indexOf(parts[i]) >= 0) return CATS[k];
      }
    }
    return '';
  }

